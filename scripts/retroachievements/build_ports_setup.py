#!/usr/bin/env python3
"""Rebuild the self-contained, local-only Ports bootstrap (development tool)."""
import base64
import io
from pathlib import Path
import shlex
import zipfile

SOURCE = Path(__file__).resolve().parent


def build():
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, 'w', compression=zipfile.ZIP_DEFLATED) as archive:
        files = [SOURCE / 'ports_setup.py', SOURCE / 'progress_ui.py', SOURCE / 'ui_palette.py', *sorted((SOURCE / 'ui-assets').iterdir())]
        for path in files:
            if not path.is_file(): continue
            info = zipfile.ZipInfo(path.relative_to(SOURCE).as_posix(), date_time=(2020, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, path.read_bytes())
    payload = base64.b64encode(buf.getvalue()).decode()
    code = ('import base64,io,subprocess,sys,tempfile,zipfile\n'
            'with tempfile.TemporaryDirectory(prefix="art-book-setup-") as folder:\n'
            f'    zipfile.ZipFile(io.BytesIO(base64.b64decode("{payload}"))).extractall(folder)\n'
            '    sys.exit(subprocess.call([sys.executable,folder+"/ports_setup.py",*sys.argv[1:]]))\n')
    return '#!/bin/sh\n# Generated by build_ports_setup.py. Copy this ONE file to share/roms/ports.\n# Embedded UI only; installs trusted local theme sources, never downloads code.\nexec python3 -c ' + shlex.quote(code) + ' "$@"\n'


if __name__ == '__main__':
    target = SOURCE / 'Install Art Book Next Features.sh'
    target.write_text(build())
    target.chmod(0o755)
