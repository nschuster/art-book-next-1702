#!/usr/bin/env python3
"""Rebuild the self-contained, local-only Ports bootstrap (development tool)."""
import base64
import io
from pathlib import Path
import shlex
import zipfile

SOURCE = Path(__file__).resolve().parent


def build():
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, 'w', compression=zipfile.ZIP_DEFLATED) as archive:
        # Explicit source allowlist: never embed private config, cache or state.
        files = [SOURCE / name for name in ('ports_actions.py', 'ports_setup.py', 'progress_ui.py', 'ui_palette.py', 'install.py', 'sync.py', 'configure.py', 'launcher.py', 'config.example.json')]
        files += sorted((SOURCE / 'ui-assets').iterdir())
        playtime = SOURCE.parent / 'system-playtime'
        extra = [(playtime / name, 'system-playtime/' + name) for name in ('install.py', 'auto_refresh.py', 'refresh.py')]
        extra.append((SOURCE.parent / 'playtime_discovery.py', 'system-playtime/playtime_discovery.py'))
        entries = [(path, path.relative_to(SOURCE).as_posix()) for path in files] + extra
        for path, archive_name in entries:
            if not path.is_file(): raise FileNotFoundError(path)
            info = zipfile.ZipInfo(archive_name, date_time=(2020, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, path.read_bytes())
    payload = base64.b64encode(buf.getvalue()).decode()
    code = ('import base64,io,subprocess,sys,tempfile,zipfile\n'
            'with tempfile.TemporaryDirectory(prefix="art-book-setup-") as folder:\n'
            f'    zipfile.ZipFile(io.BytesIO(base64.b64decode("{payload}"))).extractall(folder)\n'
            '    legacy = "--legacy-setup" in sys.argv[1:]\n'
            '    args = [a for a in sys.argv[1:] if a != "--legacy-setup"]\n'
            '    entry = "/ports_setup.py" if legacy or any(a == "--playtime" or a == "--startup" or a.startswith("--startup=") for a in args) else "/ports_actions.py"\n'
            '    sys.exit(subprocess.call([sys.executable,folder+entry,*args]))\n')
    return '#!/bin/sh\n# Generated by build_ports_setup.py. Copy this ONE file to share/roms/ports.\n# Embedded feature installers and separate Ports actions. No downloads or private state.\nexec python3 -c ' + shlex.quote(code) + ' "$@"\n'


if __name__ == '__main__':
    target = SOURCE / 'Install Art Book Next Features.sh'
    target.write_text(build())
    target.chmod(0o755)
